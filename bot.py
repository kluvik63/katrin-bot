def is_allowed(user_id: int) -> bool:
    """Проверка доступа. Если список пустой — доступ для всех."""
    if not ALLOWED_USERS:
        return True
    return user_id in ALLOWED_USERS


@dp.message(CommandStart())
async def cmd_start(message: Message):
    if not is_allowed(message.from_user.id):
        await message.answer("⛔ Доступ ограничен.")
        return
    
    uid = message.from_user.id
    conversations[uid] = []
    
    await message.answer(
        "👋 Привет! Я твой бизнес-консультант KATRIN PRO VITAMIN.\n\n"
        "Я знаю всё о твоём бизнесе и готов помочь с:\n"
        "📊 Анализом продаж и планом\n"
        "👥 Управлением персоналом\n"
        "💰 Бонусной системой и KPI\n"
        "📱 Маркетингом и контентом\n"
        "🛒 Продажами и средним чеком\n"
        "⚙️ Операционными вопросами\n\n"
        "Задавай любой вопрос — я здесь 24/7.\n\n"
        "💡 Команды:\n"
        "/clear — очистить историю диалога\n"
        "/myid — узнать свой Telegram ID"
    )


@dp.message(Command("clear"))
async def cmd_clear(message: Message):
    if not is_allowed(message.from_user.id):
        return
    conversations[message.from_user.id] = []
    await message.answer("🗑 История диалога очищена. Начинаем заново!")


@dp.message(Command("myid"))
async def cmd_myid(message: Message):
    await message.answer(f"Твой Telegram ID: `{message.from_user.id}`", parse_mode="Markdown")


@dp.message()
async def handle_message(message: Message):
    if not is_allowed(message.from_user.id):
        await message.answer("⛔ Доступ ограничен.")
        return
    
    uid = message.from_user.id
    if uid not in conversations:
        conversations[uid] = []
    
    # Добавляем сообщение пользователя
    conversations[uid].append({
        "role": "user",
        "content": message.text
    })
    
    # Ограничиваем историю (последние 20 сообщений = 10 обменов)
    if len(conversations[uid]) > 20:
        conversations[uid] = conversations[uid][-20:]
    
    # Показываем что бот думает
    await bot.send_chat_action(message.chat.id, "typing")
    
    try:
        response = claude.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=1500,
            system=SYSTEM_PROMPT,
            messages=conversations[uid]
        )
        
        reply = response.content[0].text
        
        # Сохраняем ответ в историю
        conversations[uid].append({
            "role": "assistant",
            "content": reply
        })
        
        await message.answer(reply)
        
    except Exception as e:
        logging.error(f"Ошибка Claude API: {e}")
        await message.answer(
            "⚠️ Произошла ошибка при обращении к ИИ. Попробуй ещё раз через несколько секунд."
        )


